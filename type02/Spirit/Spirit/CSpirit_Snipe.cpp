namespace BMW{
namespace Spirit{
////////////////////////////////////////////
// ステータス適用
////////////////////////////////////////////
void CSpirit_Snipe::applyStatus(SLG::CDataCharaSLG& slg, int nAttr)
{
	// 精神有効フラグを立てる
	slg.getBattle().spirit(true,Chara::CValidSpirit::SNIPE);
}

void CSpirit_Snipe::backStatus(SLG::CDataCharaSLG& slg, int nAttr)
{
	// 精神有効フラグを倒す
	slg.getBattle().spirit(false,Chara::CValidSpirit::SNIPE);
}

/////////////////////////////////////////////
// 補正
/////////////////////////////////////////////
void CSpirit_Snipe::applyOffset(SLG::COffsetRange& data)
{
	data.calcMax(+2);
	data.calcReach(+4);
}

void CSpirit_Snipe::applyOffset(SLG::COffsetHit& data)
{
	data.calcHitOff(+50);
}

/////////////////////////////////////////////
// 使用
/////////////////////////////////////////////
bool CSpirit_Snipe::enable(const SLG::CDataCharaSLG& slg, int nAttr, SLG::CSLGContext& p)
{
	// 二度掛けはできない
	if(slg.getBattle().IsSpirit(Chara::CValidSpirit::SNIPE)) return false;
	// 現在SPが消費SP(Attr)以上残ってればOK
	// ただし、集中力を持っていたら80%でいい
	if(slg.getBattle().hasSkill(Ability::CONCENT)>=0) nAttr=(nAttr*4)/5;
	return slg.getBattle().getSP()>=nAttr;
}

void CSpirit_Snipe::use(Chara::CDataCharaBattle& battle, int nAttr, SLG::CSLGContext& p)
{
	// SPを消費する
	// ただし、集中力を持っていたら80%でいい
	if(battle.hasSkill(Ability::CONCENT)>=0) nAttr=(nAttr*4)/5;
	battle.calcSP(nAttr);
}

} // namespace Spirit end
} // namespace BMW end
